#!/usr/bin/env python3
"""Builds the website's importer.js from the classic tracker's upload code (src/students.js), so both read
files exactly the same way, plus catalogue.json (the syllabus) from src/index.html."""
import json, os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = sys.argv[1]
src = open(os.path.join(root, "src", "students.js"), encoding="utf-8").read()
start = src.index("// ---------- reading files ----------")
end = src.index("$('stFiles').onchange")
body = src[start:end]
tail_old = "persist();if(touched.has(R.current))open(R.current);else if(!R.current&&touched.size)open([...touched][0]);sync.schedule();"
assert body.count(tail_old) == 1
body = body.replace(tail_old, "env.done(R,touched);")
assert body.count("list();say(") == 1
body = body.replace("list();say(", "say(")
head = r"""// Generated by tools/build-web.py from src/students.js — do not edit by hand.
function makeImporter(env){
'use strict';
const C=env.course,CAT=C.CAT;
const lessonCatalogue=CAT.lessons,initial=CAT.template,lessonLabel=C.label,setExamResult=C.setExamResult,prepare=C.prepare;
const blankState=()=>C.blank('');
const figures=s=>{const f=C.figures(s);return {o:f.overall,p:f.practical,t:f.theory}};
const clone=x=>JSON.parse(JSON.stringify(x));
const same=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
const norm=v=>String(v??'').toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
const html=v=>String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const say=m=>env.toast(m);
const today=()=>new Date().toLocaleDateString('en-CA',{timeZone:'Australia/Melbourne'});
const auDate=iso=>iso?iso.split('-').reverse().join('/'):'';
const newId=()=>crypto.randomUUID?crypto.randomUUID():Date.now().toString(36)+'-'+Math.random().toString(36).slice(2,12);
const reviewEl=document.createElement('div');reviewEl.id='stReview';reviewEl.hidden=true;
const $=id=>id==='stReview'?reviewEl:document.getElementById(id);
let R={students:{},current:null};
function addRecord(s){const uid=newId();R.students[uid]={uid,state:s,isNew:true};return uid}
"""
foot = r"""
return {reviewEl,async upload(files){if(!files.length)return;R={students:{},current:env.current()};for(const r of env.records())R.students[r.uid]=r;await upload(files)}};
}
"""
os.makedirs(out, exist_ok=True)
open(os.path.join(out, "importer.js"), "w", encoding="utf-8").write(head + body + foot)

page = open(os.path.join(root, "src", "index.html"), encoding="utf-8").read()
cat = json.loads(re.search(r"const lessonCatalogue=(\{.*?\});\n", page, re.S).group(1))
ini = json.loads(re.search(r'<script id="initial" type="application/json">(.*?)</script>', page, re.S).group(1))
order = [str(l["id"]) for l in ini["lessons"]]
ini.update({"studentId": "", "instructor": "", "course": "", "start": "", "review": "", "attendance": [], "flights": [], "milestones": {}})
for e in ini["exams"]:
    if e.get("status") in ("Not started", "In progress"):
        e["status"] = "Not attempted"
json.dump({"order": order, "lessons": cat, "template": ini}, open(os.path.join(out, "catalogue.json"), "w"))
print("importer.js + catalogue.json written")
